"""Local font delivery experiment; FontTools 4.60.2 + Brotli 1.2.1.

Run from any directory. No runtime dependency. The original font is retained.
--check verifies existing assets without writing; generating requires --generate.
"""
import argparse
import hashlib
import json
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / "public/fonts/harmonyos-sans"
SOURCE = ASSETS / "HarmonyOS_Sans_SC.woff2"
MANIFEST = ROOT / "src/styles/font-subsets.json"
CSS = ROOT / "src/styles/font-faces.css"
SOURCE_HASH = "40e3744ead7af2cb7ae3d737963745d4016a1d390b44dd68c6d0e67152aa1482"


def digest(data):
    return hashlib.sha256(data).hexdigest()


def ui_characters():
    chars = set()

    def visit(value):
        if isinstance(value, str):
            chars.update(map(ord, value))
        elif isinstance(value, dict):
            for item in value.values():
                visit(item)
        elif isinstance(value, list):
            for item in value:
                visit(item)

    for owner in ("app", "src"):
        for path in sorted((ROOT / owner).glob("**/*.json")):
            if path.parent.name not in ("locales", "_locales"):
                continue
            visit(json.loads(path.read_text()))
    return chars


def ranges(points):
    groups = []
    for point in sorted(points):
        if groups and point == groups[-1][1] + 1:
            groups[-1][1] = point
        else:
            groups.append([point, point])
    return ", ".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in groups)


def css_text(chunks):
    rules = ["/* Generated by scripts/fonts/build-subsets.py. Local experiment; see asset README. */"]
    for chunk in chunks:
        rules.append(f'''@font-face {{
  font-family: "HarmonyOS Sans SC";
  src: url("/fonts/harmonyos-sans/subsets/{chunk['file']}") format("woff2");
  font-style: normal;
  font-weight: 40 900;
  font-display: swap;
  unicode-range: {ranges(chunk['codepoints'])};
}}''')
    return "\n\n".join(rules) + "\n"


def verify_font(original, derived, points, support=()):
    original_map = original.getBestCmap()
    original_names = set(original.getGlyphOrder())
    assert set(derived.getBestCmap()) == set(points) | set(support), "Subset cmap mismatch"
    for attr in ("xMin", "yMin", "xMax", "yMax"):
        assert getattr(derived["head"], attr) == getattr(original["head"], attr), attr
    assert derived['fvar'].compile(derived) == original['fvar'].compile(original), "Weight axis changed"
    for table, attributes in {
        'hhea': ('ascent', 'descent', 'lineGap'),
        'OS/2': ('sTypoAscender', 'sTypoDescender', 'sTypoLineGap', 'usWinAscent', 'usWinDescent'),
    }.items():
        for attr in attributes:
            assert getattr(derived[table], attr) == getattr(original[table], attr), (table, attr)
    for name in derived.getGlyphOrder():
        assert name in original_names, name
        # Flatten composite outlines so glyph-index renumbering is irrelevant.
        before = original['glyf'][name].getCoordinates(original['glyf'])
        after = derived['glyf'][name].getCoordinates(derived['glyf'])
        assert before == after, f"Outline changed: {name}"
        def instructions(font):
            program = getattr(font['glyf'][name], 'program', None)
            return bytes(program.getBytecode()) if program else b''
        assert instructions(original) == instructions(derived), f"Hint instructions changed: {name}"
        for table in ('hmtx', 'vmtx'):
            assert original[table][name] == derived[table][name], (table, name)
        def variations(font):
            return [(v.axes, v.coordinates) for v in font['gvar'].variations.get(name, [])]
        assert variations(original) == variations(derived), f"Variation changed: {name}"
    for point in points:
        assert derived.getBestCmap()[point] == original_map[point], point


def generate_chunk(group):
    label, points, support, source_path = group
    source = TTFont(source_path, lazy=True, recalcTimestamp=False, recalcBBoxes=False)
    out = ASSETS / "subsets"
    for cached in out.glob(f"{label}.*.woff2"):
        cached_font = TTFont(cached, lazy=True)
        matching_bounds = all(getattr(cached_font['head'], k) == getattr(source['head'], k) for k in ('xMin', 'yMin', 'xMax', 'yMax'))
        if set(cached_font.getBestCmap()) == points | support and matching_bounds and cached_font['OS/2'].ulUnicodeRange1 == source['OS/2'].ulUnicodeRange1:
            data = cached.read_bytes()
            return dict(file=cached.name, bytes=len(data), sha256=digest(data), codepoints=sorted(points))
    font = source
    options = subset.Options()
    options.name_IDs = ['*']
    options.name_languages = ['*']
    options.name_legacy = True
    options.glyph_names = True
    options.notdef_outline = True
    options.layout_features = ['*']
    options.recalc_timestamp = False
    options.prune_unicode_ranges = False
    options.prune_codepage_ranges = False
    worker = subset.Subsetter(options=options)
    worker.populate(unicodes=points | support)
    worker.subset(font)
    import io
    buffer = io.BytesIO()
    font.flavor = 'woff2'
    font.save(buffer)
    data = buffer.getvalue()
    sha = digest(data)
    filename = f'{label}.{sha[:12]}.woff2'
    (out / filename).write_bytes(data)
    print(f"Generated {filename}: {len(points)} characters, {len(data)} bytes", flush=True)
    return dict(file=filename, bytes=len(data), sha256=sha, codepoints=sorted(points))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--generate', action='store_true')
    mode.add_argument('--check', action='store_true')
    args = parser.parse_args()
    assert digest(SOURCE.read_bytes()) == SOURCE_HASH, "Unexpected source font"
    original = TTFont(SOURCE, lazy=True, recalcTimestamp=False, recalcBBoxes=False)
    coverage = set(original.getBestCmap())
    chars = ui_characters()
    assert chars <= coverage, "UI includes characters absent from original font"
    if args.generate:
        latin = {cp for cp in coverage if cp <= 0x24F}
        # Keep UI punctuation with Latin so English does not fetch Chinese glyphs.
        latin |= {cp for cp in chars if not 0x3400 <= cp <= 0x9FFF}
        common = chars - latin
        remaining = sorted(coverage - latin - common)
        groups = [('latin', latin, latin), ('ui', common, latin)]
        groups.extend((f'other-{i // 512:03}', set(remaining[i:i + 512]), latin) for i in range(0, len(remaining), 512))
        out = ASSETS / 'subsets'
        out.mkdir(exist_ok=True)
        chunks = []
        from concurrent.futures import ProcessPoolExecutor
        from tempfile import TemporaryDirectory
        # Decode the full WOFF2 only once. Workers subset a temporary sfnt;
        # repeatedly reconstructing all 29,824 WOFF2 glyphs is needlessly slow.
        with TemporaryDirectory(prefix="ori-font-source-") as temporary:
            decoded = Path(temporary) / "source.ttf"
            original.flavor = None
            original.save(decoded)
            original.flavor = "woff2"
            with ProcessPoolExecutor(max_workers=4) as pool:
                chunks = list(pool.map(generate_chunk, [(*group, decoded) for group in groups]))
        MANIFEST.write_text(json.dumps(dict(sourceSha256=SOURCE_HASH, supportCodepoints=sorted(latin), chunks=chunks), indent=2) + '\n')
        CSS.write_text(css_text(chunks))
    manifest = json.loads(MANIFEST.read_text())
    assert manifest['sourceSha256'] == SOURCE_HASH
    seen = set()
    for chunk in manifest['chunks']:
        points = set(chunk['codepoints'])
        assert not seen & points, 'Overlapping unicode ranges'
        seen |= points
        path = ASSETS / 'subsets' / chunk['file']
        data = path.read_bytes()
        assert len(data) == chunk['bytes'] and digest(data) == chunk['sha256']
        verify_font(original, TTFont(path, lazy=True), points, manifest['supportCodepoints'])
    assert seen == coverage, 'Original coverage lost'
    primary = set(manifest['chunks'][0]['codepoints'] + manifest['chunks'][1]['codepoints'])
    assert chars <= primary, 'Regenerate subsets for new UI characters'
    # Ignore formatter whitespace but verify the exact declarations and ranges.
    assert ''.join(CSS.read_text().split()) == ''.join(css_text(manifest['chunks']).split())
    print(f"PASS: {len(seen)} mappings; outlines, metrics, variations and 40–900 axis preserved across {len(manifest['chunks'])} subsets.")
    print('UI font bytes:', sum(c['bytes'] for c in manifest['chunks'][:2]))
    if args.generate:
        referenced = {chunk['file'] for chunk in manifest['chunks']}
        for path in (ASSETS / 'subsets').glob('*.woff2'):
            if path.name not in referenced:
                path.unlink()


if __name__ == '__main__':
    main()
